#!/usr/bin/env python3
"""Paired, descriptive effect analysis for the corrected benchmark.

Differences are computed for the same held-out vendor and random seed, with
method minus ERM as the sign convention. Bootstrap intervals summarize these
nine paired units; they are descriptive because seeds are not independent
datasets.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "results/corrected_benchmark.json"
OUTPUT = ROOT / "results/corrected_method_effects.json"
TABLE = ROOT / "paper/generated_method_effects_table.tex"
RNG_SEED = 20260809
N_BOOTSTRAP = 10000


def bootstrap_interval(values: np.ndarray) -> tuple[float, float]:
    rng = np.random.default_rng(RNG_SEED)
    samples = rng.choice(values, size=(N_BOOTSTRAP, len(values)), replace=True)
    means = samples.mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def summarize(deltas: np.ndarray) -> dict:
    low, high = bootstrap_interval(deltas)
    return {
        "n_pairs": int(len(deltas)),
        "mean_delta_ms": float(deltas.mean()),
        "sd_delta_ms": float(deltas.std(ddof=1)),
        "bootstrap_ci95_ms": [low, high],
        "wins_against_erm": int(np.sum(deltas < 0)),
        "ties": int(np.sum(deltas == 0)),
        "losses_against_erm": int(np.sum(deltas > 0)),
    }


def main() -> None:
    results = json.loads(INPUT.read_text())
    algorithms = list(results["protocol"]["algorithms"])
    if "erm" not in algorithms:
        raise ValueError("ERM is required as the paired reference")

    by_key: dict[tuple[str, str], dict[str, dict]] = {}
    for vendor, fold in results["leave_one_vendor_out"].items():
        for algorithm, runs in fold["algorithms"].items():
            for run in runs:
                by_key.setdefault((vendor, str(run["seed"])), {})[algorithm] = run

    output = {
        "schema_version": "corrected-method-effects-v1",
        "protocol": {
            "reference": "ERM",
            "paired_unit": "held-out vendor x random seed",
            "difference": "method target error minus ERM target error",
            "bootstrap_replicates": N_BOOTSTRAP,
            "bootstrap_seed": RNG_SEED,
            "target_labels_used": False,
            "interpretation": "descriptive; random seeds are not independent datasets",
        },
        "methods": {},
    }

    for algorithm in algorithms:
        if algorithm == "erm":
            continue
        deltas = {key: [] for key in ("mae", "mae_t1", "mae_t2")}
        units = []
        for (vendor, seed), records in sorted(by_key.items()):
            if algorithm not in records or "erm" not in records:
                raise ValueError(f"missing paired record for {vendor}/{seed}/{algorithm}")
            method_target = records[algorithm]["target"]
            erm_target = records["erm"]["target"]
            units.append({"vendor": vendor, "seed": int(seed)})
            for key in deltas:
                deltas[key].append(float(method_target[key] - erm_target[key]))
        output["methods"][algorithm] = {
            "paired_units": units,
            "pooled": {
                metric: summarize(np.asarray(values, dtype=np.float64))
                for metric, values in deltas.items()
            },
        }

    OUTPUT.write_text(json.dumps(output, indent=2) + "\n")

    lines = [
        "% Generated by scripts/analyze_benchmark_effects.py.",
        "\\resizebox{\\linewidth}{!}{%",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Method & $\\Delta$ MAE (ms) & 95\\% bootstrap CI & Wins & Losses \\\\",
        "\\midrule",
    ]
    for algorithm, details in output["methods"].items():
        pooled = details["pooled"]["mae"]
        low, high = pooled["bootstrap_ci95_ms"]
        lines.append(
            f"{algorithm.upper()} & {pooled['mean_delta_ms']:.1f} & "
            f"[{low:.1f}, {high:.1f}] & {pooled['wins_against_erm']} & "
            f"{pooled['losses_against_erm']} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", "}"])
    TABLE.write_text("\n".join(lines) + "\n")
    print(f"Saved {OUTPUT}")
    print(f"Saved {TABLE}")


if __name__ == "__main__":
    main()
